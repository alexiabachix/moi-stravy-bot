def all_recipes_in_section(recipes_dict, section):
    """Повертає список усіх рецептів з усіх підкатегорій обраного розділу."""
    items = []
    for subcat, recipes in recipes_dict.get(section, {}).items():
        for r in recipes:
            items.append((subcat, r))
    return items


async def send_menu(query, text, keyboard):
    """Видаляє поточне повідомлення і надсилає нове текстове меню
    (повідомлення з фото не можна перетворити на текстове напряму)."""
    chat_id = query.message.chat_id
    try:
        await query.message.delete()
    except Exception:
        pass
    await query.get_bot().send_message(
        chat_id=chat_id,
        text=text,
        reply_markup=InlineKeyboardMarkup(keyboard),
    )


async def send_recipe_view(query, recipe, keyboard):
    """Показує рецепт (з фото чи без) із переданою клавіатурою."""
    chat_id = query.message.chat_id
    try:
        await query.message.delete()
    except Exception:
        pass
    caption = f"*{recipe['title']}*\n\n{recipe['text']}"
    markup = InlineKeyboardMarkup(keyboard)
    if recipe.get("photo"):
        await query.get_bot().send_photo(
            chat_id=chat_id,
            photo=recipe["photo"],
            caption=caption,
            parse_mode="Markdown",
            reply_markup=markup,
        )
    else:
        await query.get_bot().send_message(
            chat_id=chat_id,
            text=caption,
            parse_mode="Markdown",
            reply_markup=markup,
        )


def main_menu_keyboard(lang):
    cfg = LANGS[lang]
    keyboard = [[InlineKeyboardButton(section, callback_data=f"section|{lang}|{section}")] for section in cfg["sections"]]
    keyboard.append([InlineKeyboardButton(cfg["random_button"], callback_data=f"random_menu|{lang}")])
    other_lang = "es" if lang == "uk" else "uk"
    keyboard.append([InlineKeyboardButton(cfg["switch_button"], callback_data=f"switch_lang|{other_lang}")])
    return keyboard


async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        LANGS["uk"]["choose_section"],
        reply_markup=InlineKeyboardMarkup(main_menu_keyboard("uk")),
    )


